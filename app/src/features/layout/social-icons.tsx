const INLINE_SOCIAL_BRAND_ICONS = new Set(["telegram", "tiktok", "whatsapp", "instagram", "facebook"])

export function hasInlineSocialBrandIcon(id: string): boolean {
  return INLINE_SOCIAL_BRAND_ICONS.has(id)
}

export function SocialBrandIcon({
  id,
  className,
  ...props
}: { id: string } & SVGProps<SVGSVGElement>) {
  if (id === "telegram") return <TelegramIcon className={className} {...props} />
  if (id === "tiktok") return <TikTokIcon className={className} {...props} />
  if (id === "whatsapp") return <WhatsAppIcon className={className} {...props} />
  if (id === "instagram") return <InstagramIcon className={className} {...props} />
  if (id === "facebook") return <FacebookIcon className={className} {...props} />
  return null
}

export function SocialLinkIcon({
  id,
  iconSrc,
  className,
}: {
  id: string
  iconSrc?: string
  className?: string
}) {
  if (hasInlineSocialBrandIcon(id)) {
    return <SocialBrandIcon id={id} className={className} />
  }
  if (iconSrc) {
    return <img src={iconSrc} alt="" className={className} aria-hidden />
  }
  return null
}
